import type { HttpResponse, RuleViolationLocation } from '@thymian/core';
import { getHeader, requestHeader } from '@thymian/core';
import { httpRule } from '@thymian/core';

import {
  type ByteRange,
  formatByteRange,
  intRanges,
  parseRangeHeader,
  unparsableRangeHeader,
} from './utils.js';

const NAME = 'rfc9110/client-should-list-multiple-ranges-in-ascending-order';

function validateRangeOrder(ranges: ByteRange[]): string | undefined {
  const listed = intRanges(ranges);

  for (let i = 0; i < listed.length - 1; i++) {
    const current = listed[i];
    const next = listed[i + 1];

    if (!current || !next) {
      continue;
    }

    if (next.first < current.first) {
      return `Inefficient order: Range ${formatByteRange(next)} appears after ${formatByteRange(current)}.
                  Ranges should be listed in ascending order to optimize server-side processing and representation flow.`;
    }
  }

  return;
}

// eslint-disable-next-line thymian-internal/require-rule-tags -- no concern-tag member fits this rule's topic
export default httpRule(NAME)
  .severity('warn')
  // A request-side ("client SHOULD") rule, so it is valid only in `analyze` — in
  // `test` the request is generated by Thymian, not a real client.
  .type('analytics')
  .url('https://www.rfc-editor.org/rfc/rfc9110.html#name-range')
  .description(
    'A client that is requesting multiple ranges SHOULD list those ranges in ascending order (the order in which they would typically be received in a complete representation) unless there is a specific need to request a later part earlier.',
  )
  .summary(
    'Client should list multiple ranges in ascending order unless there is a specific need to request a later part earlier.',
  )
  .explanation(
    'When you ask for several byte ranges at once, list them in increasing order, the same order they appear in the full resource, unless you have a real reason to fetch a later part first. Ordered ranges let the server read and stream the representation in one forward pass; jumbled ranges force extra seeking and can look like a broken client or an attack, so servers may treat scrambled requests less favorably.',
  )
  .appliesTo('client')
  .rule((ctx) =>
    ctx.validateHttpTransactions({
      appliesTo: requestHeader('range'),
      violatedWhen: (
        req,
        _res: HttpResponse,
        location: RuleViolationLocation,
      ) => {
        const rangeHeader = getHeader(req.headers, 'range');

        if (rangeHeader === undefined) {
          return [];
        }

        const ranges = parseRangeHeader(rangeHeader);

        if (!ranges) {
          return [unparsableRangeHeader(NAME, location, rangeHeader)];
        }

        const result = validateRangeOrder(ranges);

        if (result) {
          return [{ location, violation: { message: result }, findings: [] }];
        } else {
          return [];
        }
      },
    }),
  )
  .done();
